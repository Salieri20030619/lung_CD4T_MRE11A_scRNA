def bh(p):
 p=np.asarray(p,float);q=np.full(len(p),np.nan);k=np.flatnonzero(np.isfinite(p));o=k[np.argsort(p[k])];q[o]=np.minimum(1,np.minimum.accumulate((p[o]*len(o)/np.arange(1,len(o)+1))[::-1])[::-1]);return q
